#!/usr/bin/env python3
"""S8.1 snippet harness - PLAN.md 8/R3: every code fence a page publishes must build.

Usage: tools/make-samples.py [--list] [--keep] [--verbose] [--tcell DIR] [page ...]

How a page declares code (PLAN.md 7 freezes the `go` fence tag; these markers are the rest of that
contract and tools/check-style.py validates their spelling):

    ```go                       standard: a complete, runnable program (package main + func main)
    ```go snippet=hello         part of snippet "hello"; all fences with the same name are
                                concatenated in document order into one program
    ```go mode=lib              a fragment: type-checked, not linked. With no `package` clause,
                                `package main` is prepended so a page can show a bare func
    ```go mode=skip             not compiled: terminal transcripts, v2 comparisons, pseudo-code
    ```go headless=yes          mode=program only: after it builds, run it with no real terminal
                                (S8.6) - vt.MockTerm + tcell.ShimScreen, ESC must quit the program

Everything runs in a throwaway sandbox: samples/go.mod and go.sum are copied, page snippets are
written under gen/, and gofmt/go vet/go build (plus go test for headless=yes) run there. Nothing is
generated into the repo, so there is nothing to keep in sync and nothing to gitignore.
`go mod edit -replace` points the sandbox at --tcell (default $TCELL_DIR, else ../tcell), which is how
CI builds against a fresh clone.

The headless recipe is taken from the library's own tests (../tcell/demos/hello/hello_test.go), which
is also why the wiki links those demos instead of re-authoring examples: ShimScreen makes the mock the
screen that tcell.NewScreen() returns, so a page's program runs unchanged. PLAN.md S8.6 asked whether
Screen.Init works against the mock - it does, so S8.6 stands and is opt-in per fence.

Exit 0 = every snippet compiles, 1 = a snippet is broken or mislabelled, 2 = environment problem
(no Go, no tcell checkout, no samples/go.mod).
"""
from __future__ import annotations

import argparse
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import wikilib as W

SAMPLES = W.ROOT / "samples"
MODULE = "github.com/gdamore/tcell/v3"
MODES = {"program", "lib", "skip"}
HEADLESS = {"yes", "no"}

# Written next to a program snippet that asks for headless=yes (S8.6). Modelled on
# ../tcell/demos/hello/hello_test.go, so the mock screen is set up the way upstream sets it up.
HEADLESS_TEST = '''// Code generated by tools/make-samples.py from the fence at {where}. DO NOT EDIT.

package main

import (
	"strings"
	"testing"
	"time"

	"github.com/gdamore/tcell/v3"
	"github.com/gdamore/tcell/v3/vt"
)

func TestHeadless(t *testing.T) {{
	mt := vt.NewMockTerm(vt.MockOptColors(8))
	scr, err := tcell.NewTerminfoScreenFromTty(mt, tcell.OptColors(8), tcell.OptTerm("ansi"))
	if err != nil {{
		t.Fatalf("NewTerminfoScreenFromTty: %v", err)
	}}
	tcell.ShimScreen(scr)

	done := make(chan struct{{}})
	go func() {{ main(); close(done) }}()

	deadline := time.Now().Add(3 * time.Second)
	var drawn []string
	for time.Now().Before(deadline) && len(drawn) == 0 {{
		time.Sleep(10 * time.Millisecond)
		_ = mt.Drain()
		for y := vt.Row(0); y < 24; y++ {{
			for x := vt.Col(0); x < 80; x++ {{
				if c := string(mt.GetCell(vt.Coord{{X: x, Y: y}}).C); strings.TrimSpace(c) != "" {{
					drawn = append(drawn, c)
				}}
			}}
		}}
	}}
	if len(drawn) == 0 {{
		t.Fatal("program ran but drew nothing on the emulated screen")
	}}

	mt.KeyTap(vt.KeyEsc)
	select {{
	case <-done:
	case <-time.After(3 * time.Second):
		t.Fatal("program did not exit after ESC - a wiki snippet must have an ESC arm")
	}}
}}
'''



def slug(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]", "_", text)


class Snippet:
    """One compiled unit: a whole fence, or several fences with the same snippet= name."""

    def __init__(self, page, lineno, mode, name, body, named):
        self.page = page
        self.lineno = lineno
        self.mode = mode
        self.headless = False
        self.name = name
        self.named = named
        self.parts = [body]
        self.status = "not-compiled"
        self.detail = ""
        self.dir = ""

    @property
    def where(self) -> str:
        return f"{self.page}:{self.lineno}"

    @property
    def source(self) -> str:
        return "\n".join(self.parts).strip("\n") + "\n"


def parse_info(info: str):
    """'go mode=lib snippet=hello' -> ('go', {'mode': 'lib', 'snippet': 'hello'})."""
    tokens = info.split()
    lang = tokens[0] if tokens else ""
    kv = {}
    for tok in tokens[1:]:
        key, sep, val = tok.partition("=")
        if sep:
            kv[key] = val
    return lang, kv


def extract(pages):
    """Every go fence on the pages, in order; named fences merged."""
    out, by_name = [], {}
    for path in pages:
        text = W.read(path)
        try:
            rel = path.resolve().relative_to(W.ROOT).as_posix()
        except ValueError:
            rel = path.name
        number = 0
        for lineno, info, body in W.fence_blocks(text):
            if info is None:
                continue  # unclosed fences are check-style.py's job
            lang, kv = parse_info(info)
            if lang != "go":
                continue
            number += 1
            mode = kv.get("mode", "program")
            name = kv.get("snippet")
            headless = kv.get("headless", "no")
            if mode not in MODES:
                out.append(Snippet(rel, lineno, "skip", f"bad-mode{number:02d}", "", False))
                out[-1].status = f"label: mode={mode} is not one of {sorted(MODES)}"
                continue
            if headless not in HEADLESS:
                out.append(Snippet(rel, lineno, "skip", f"bad-headless{number:02d}", "", False))
                out[-1].status = f"label: headless={headless} is not one of {sorted(HEADLESS)}"
                continue
            if headless == "yes" and mode != "program":
                out.append(Snippet(rel, lineno, "skip", f"bad-headless{number:02d}", "", False))
                out[-1].status = (f"label: headless=yes needs the default mode=program - a fragment "
                                  f"has no main() to run (mode={mode})")
                continue
            if name:
                if name in by_name:
                    by_name[name].parts.append("\n".join(body))
                    by_name[name].headless = by_name[name].headless or headless == "yes"
                    continue
                snip = Snippet(rel, lineno, mode, name, "\n".join(body), True)
                snip.headless = headless == "yes"
                by_name[name] = snip
                out.append(snip)
                continue
            out.append(Snippet(rel, lineno, mode, f"{slug(rel)}-{number:02d}",
                               "\n".join(body), False))
            out[-1].headless = headless == "yes"
    return out


def prepare(snips, sandbox: pathlib.Path):
    """Write the compilable snippets into the sandbox; mark the rest. Returns written snippets."""
    written = []
    for snip in snips:
        if snip.status.startswith("label"):
            continue
        if snip.mode == "skip":
            snip.status = "skipped"
            continue
        src = snip.source
        if not src.strip():
            snip.status = "label: fence contains no code"
            continue
        if snip.mode == "program":
            if "package main" not in src:
                snip.status = ("label: no 'package main' - a plain ```go fence must be a complete "
                               "program; use mode=lib for a fragment, mode=skip for pseudo-code")
                continue
            if not re.search(r"\bfunc main\(", src):
                snip.status = "label: no 'func main()' - add one or make the fence mode=lib"
                continue
        elif snip.mode == "lib" and not re.search(r"^\s*package\s+\w+", src, re.M):
            src = "package main\n\n" + src
            snip.detail = "(injected 'package main')"
        snip.dir = f"gen/{slug(snip.name)}"
        dest = sandbox / snip.dir
        dest.mkdir(parents=True, exist_ok=True)
        (dest / "main.go").write_text(src, encoding="utf-8")
        snip.status = "written"
        written.append(snip)
    return written


def run(cmd, cwd):
    p = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True)
    return p.returncode, (p.stdout + p.stderr).strip()


def main() -> int:
    ap = argparse.ArgumentParser(description="S8.1 wiki snippet compile harness")
    ap.add_argument("pages", nargs="*", help="pages to scan (default: tools/pages.txt)")
    ap.add_argument("--tcell", default=os.environ.get("TCELL_DIR")
                    or str((W.ROOT.parent / "tcell").resolve()),
                    help="tcell checkout to build against (default $TCELL_DIR or ../tcell)")
    ap.add_argument("--list", action="store_true", help="print the snippets and exit")
    ap.add_argument("--keep", action="store_true", help="keep the sandbox and print its path")
    ap.add_argument("--verbose", "-v", action="store_true")
    args = ap.parse_args()

    pages = W.page_paths(args.pages or None)
    missing = [p for p in pages if not p.exists()]
    if missing:
        for p in missing:
            print(f"{p}: listed file does not exist", file=sys.stderr)
        return 2
    tcell = pathlib.Path(args.tcell).resolve()
    if not (tcell / "go.mod").is_file():
        print(f"error: {tcell} has no go.mod; pass --tcell or set TCELL_DIR "
              "(PLAN.md assumes the sibling checkout ../tcell)", file=sys.stderr)
        return 2
    if subprocess.run(["bash", "-lc", "command -v go"], capture_output=True).returncode != 0:
        print("error: go not on PATH; S8.1 needs a toolchain", file=sys.stderr)
        return 2
    if not (SAMPLES / "go.mod").is_file():
        print("error: samples/go.mod is missing (the harness module itself)", file=sys.stderr)
        return 2

    snips = extract(pages)
    fences = sum(len(s.parts) for s in snips)
    named_multi = sorted(s.name for s in snips if s.named and len(s.parts) > 1)
    print(f"snippets  {fences} go fence(s) on {len(pages)} page(s) -> {len(snips)} snippet(s), "
          f"{len([s for s in snips if s.mode == 'skip' and not s.status.startswith('label')])} "
          f"marked mode=skip, {len([s for s in snips if s.headless])} marked headless=yes (S8.6)"
          + (f"; written across fences: {', '.join(named_multi)}" if named_multi else ""))
    if args.list:
        for s in snips:
            print(f"  {s.where}  mode={s.mode}  {s.name}")
        return 0

    sandbox = pathlib.Path(tempfile.mkdtemp(prefix="tcell-wiki-samples-"))
    for name in ("go.mod", "go.sum"):
        if (SAMPLES / name).is_file():
            shutil.copy2(SAMPLES / name, sandbox / name)

    written = prepare(snips, sandbox)

    rc, out = run(["go", "mod", "edit", f"-replace={MODULE}={tcell}"], sandbox)
    if rc != 0:
        print(f"cannot retarget the sandbox at {tcell}:\n{out}", file=sys.stderr)
        return 2

    def build(what: str, extra=()):
        return run(["go", "build", *extra, what], sandbox)

    # gofmt on the generated sources only if there are any (a page may have no code yet).
    fmt_targets = [str(rel) for rel in ("gen",) if (sandbox / rel).exists()]
    rc_fmt, fmt_out = run(["gofmt", "-l", *fmt_targets], sandbox) if fmt_targets else (0, "")
    unformatted = [f.strip() for f in fmt_out.splitlines() if f.strip()]
    fmt_diff = {}
    for f in unformatted:
        rc_d, diff = run(["gofmt", "-d", f], sandbox)
        del rc_d
        fmt_diff[f] = diff

    # A page set with no code fences has nothing to vet - `go vet ./...` in an empty module is an
    # error ("matched no packages"), and today both real pages are like that.
    if written:
        rc_vet, vet_out = run(["go", "vet", "./..."], sandbox)
        if rc_vet != 0 and "missing go.sum entry" in vet_out:
            rc_tidy, tidy_out = run(["go", "mod", "tidy"], sandbox)
            if rc_tidy == 0:
                rc_vet, vet_out = run(["go", "vet", "./..."], sandbox)
            else:
                print(f"go mod tidy failed inside the sandbox (the harness is broken, not a page):\n"
                      f"{tidy_out}", file=sys.stderr)
                return 2
    else:
        rc_vet, vet_out = 0, ""

    # mode=program gets a real link (that is the only way to catch a missing func main);
    # mode=lib is type-checked by the module-wide `go vet ./...` above and must not be linked,
    # because a fragment legitimately has no main() - linking it is an error the page cannot fix.
    fails = []
    (sandbox / "bin").mkdir(exist_ok=True)
    for snip in written:
        if snip.mode != "program":
            snip.status = ("type-checked by go vet " + snip.detail).strip()
            if rc_vet != 0:
                snip.status, snip.detail = "BUILD FAILED", vet_out
                fails.append(snip)
            continue
        rc, out = build(f"./{snip.dir}", extra=("-o", f"bin/{slug(snip.name)}",))
        snip.status = "builds + links" if rc == 0 else "BUILD FAILED"
        if rc != 0:
            snip.detail = out
            fails.append(snip)

    # S8.6: a snippet that asks for it is also *run*, headless, on the vt emulator. Only after it
    # builds, because a compile error inside a snippet whose test file we generated reads as if the
    # harness were broken.
    for snip in written:
        if not snip.headless or snip.status != "builds + links":
            continue
        (sandbox / snip.dir / "headless_test.go").write_text(
            HEADLESS_TEST.format(where=snip.where), encoding="utf-8")
        rc, out = run(["go", "test", "-run", "TestHeadless", "-timeout", "90s", f"./{snip.dir}"],
                      sandbox)
        snip.detail = out
        if rc == 0:
            snip.status = "builds + links + runs headless"
        else:
            snip.status = "HEADLESS FAILED"
            fails.append(snip)

    def translate(text: str) -> str:
        """Rewrite sandbox paths so the error points at the page and line that produced them."""
        for s in written:
            if s.dir:
                text = re.sub(re.escape(f"{s.dir}/main.go"), s.where, text)
                text = re.sub(re.escape(s.dir) + r"\b", s.where, text)
        return text

    problems = [f"{s.where}: {s.status.replace('label: ', '')}" for s in snips
                if s.status.startswith("label")]
    for snip in fails:
        detail = translate(snip.detail)
        if snip.status == "HEADLESS FAILED":
            extra = ("  (PLAN.md 7: a program a reader runs must quit - draw, Show, then exit on ESC)"
                     if "ESC" in detail else "")
            problems.append(f"{snip.where}: builds but does not run headless on vt.MockTerm (S8.6):"
                            f"\n{detail}{extra}")
            continue
        missing = sorted(set(re.findall(r"undefined: ([A-Za-z_][\w.]*)", detail)))
        hint = ""
        if missing and re.search(r"\btcell\b", detail):
            hint = ("\n         PLAN.md 7 requires snippets to show their imports: add the import block "
                    "(the v3 module path and subpackages such as .../color) inside the fence - undefined: "
                    + ", ".join(missing))
        elif missing:
            hint = f"\n         undefined: {', '.join(missing)} - add the import, or fix the name"
        problems.append(f"{snip.where}: does not build against {tcell}\n{detail}{hint}")
    for f in unformatted:
        src = next((sn.where for sn in written if sn.dir and f.startswith(sn.dir)), f)
        problems.append(f"{src}: snippet is not gofmt-clean. PLAN.md 7 wants gofmt-ready code, so "
                        f"fix the page text itself; the patch gofmt wants:\n{fmt_diff.get(f, '')}")
    if rc_vet != 0:
        if fails:
            problems.append("go vet also reported errors - fix the builds above first, then re-run")
        else:
            problems.append("go vet failed (this one is not tied to a single page):\n" + translate(vet_out))

    for s in snips:
        if args.verbose or s.status != "written":
            print(f"  {s.where}  {s.mode:<7}  {s.name:<28}  {s.status}")

    if problems:
        print()
        for p in problems:
            print(f"SNIPPET  {p}")
        print(f"\n{len(problems)} snippet problem(s): a page may publish only code that builds.")
    else:
        print(f"snippets: clean - {len(written)} compiled "
              f"({len([s for s in written if s.mode == 'program'])} program(s), "
              f"{len([s for s in written if s.mode == 'lib'])} fragment(s)), "
              f"{len([s for s in snips if s.status == 'skipped'])} skipped, "
              f"gofmt clean, against {tcell}")

    if args.keep:
        print(f"sandbox kept: {sandbox}")
    elif not args.verbose:
        shutil.rmtree(sandbox, ignore_errors=True)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
